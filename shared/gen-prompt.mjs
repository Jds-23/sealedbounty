// Regenerates system-prompt.mjs + system-prompt.sha256 from system-prompt.txt (the source of truth).
// system-prompt.txt is stored WITHOUT a trailing newline; its exact bytes are the prompt.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

const here = (p) => new URL(p, import.meta.url);
const prompt = readFileSync(here('./system-prompt.txt'), 'utf8');
if (prompt.endsWith('\n')) throw new Error('system-prompt.txt must not end with a newline');
const hash = createHash('sha256').update(prompt, 'utf8').digest('hex');
writeFileSync(here('./system-prompt.sha256'), hash); // no trailing newline either
writeFileSync(
  here('./system-prompt.mjs'),
  `// GENERATED by gen-prompt.mjs from system-prompt.txt. Do not edit.\n` +
    `/** Frozen judge system prompt (exact string; no trailing newline). */\n` +
    `export const SYSTEM_PROMPT = ${JSON.stringify(prompt)};\n` +
    `/** sha256 hex of utf8(SYSTEM_PROMPT) == Program.system_prompt_hash. */\n` +
    `export const SYSTEM_PROMPT_SHA256 = ${JSON.stringify(hash)};\n`,
);
console.log(hash);
